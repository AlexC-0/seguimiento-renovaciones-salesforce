'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { connectP06, reportError, root, privateDir, readState, writeState } = require('./salesforce.cjs');
(async () => {
  const c = await connectP06(process.argv[2]);
  const stage = process.argv[3];
  if (!['primero', 'repeticion'].includes(stage)) throw Error('Etapa inválida.');
  const state = readState('demostracion.json');
  const currentCut = new Intl.DateTimeFormat('en-CA', { timeZone: state.timezone }).format(new Date());
  if (currentCut !== state.cut) throw Error('Ha cambiado la fecha del solicitante; revisar el conjunto antes de lanzar.');
  if (state.runs[stage]) throw Error('El lanzamiento ya tiene intención registrada; no se repite automáticamente.');
  if (stage === 'repeticion' && !state.runs.primero?.verified) throw Error('El primer trabajo no está comprobado.');
  const ids = state.contracts.map(x => x.id);
  if (ids.length !== 124 || ids.some(x => !/^[A-Za-z0-9]{18}$/.test(x))) throw Error('Alcance inesperado.');
  const rows = (await c.query("SELECT Id, Cuenta__c, Estado__c, FechaVencimiento__c FROM ContratoComercial__c WHERE Id IN ('" + ids.join("','") + "')")).records;
  const end = new Date(new Date(state.cut + 'T12:00:00Z').getTime() + 30 * 86400000).toISOString().slice(0, 10);
  if (rows.length !== 124 || rows.some(r => r.Cuenta__c !== state.accountId)) throw Error('El filtro incluye registros ajenos a la demostración.');
  const candidates = rows.filter(r => r.Estado__c === 'Activo' && r.FechaVencimiento__c >= state.cut && r.FechaVencimiento__c <= end);
  if (candidates.length !== 120) throw Error('Candidatos distintos de los previstos.');
  const prior = (await c.query("SELECT FIELDS(ALL) FROM SeguimientoRenovacion__c WHERE Contrato__c IN ('" + ids.join("','") + "') LIMIT 200")).records;
  if (prior.length !== (stage === 'primero' ? 0 : 120)) throw Error('Conteo previo inesperado.');
  writeState('seguimientos-antes-' + stage + '.json', prior);
  const template = fs.readFileSync(path.join(root, 'scripts/fase-3/lanzar-renovaciones.apex'), 'utf8');
  const source = template.replace('// ALCANCE_P06', ids.map(x => "'" + x + "'").join(',\n    '));
  fs.writeFileSync(path.join(privateDir, 'lanzamiento-' + stage + '.apex'), source);
  state.runs[stage] = { preparedAt: new Date().toISOString(), expectedCandidates: 120, beforeFollows: prior.length, batchSize: 50, sourceHash: crypto.createHash('sha256').update(source).digest('hex') };
  writeState('demostracion.json', state);
  fs.writeFileSync(path.join(root, 'docs/evidencias-fase-3/previo-' + stage + '.json'), JSON.stringify({ stage, ...state.runs[stage], cut: state.cut, end, contractIds: ids, candidateIds: candidates.map(x => x.Id) }, null, 2) + '\n');
  console.log(JSON.stringify({ stage, expectedCandidates: 120, filterSize: ids.length, beforeFollows: prior.length, batchSize: 50, sourcePrepared: true }));
})().catch(reportError);
